-- Create database if not exists
CREATE DATABASE IF NOT EXISTS student_management_db
CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

USE student_management_db;

-- Table: departments
CREATE TABLE IF NOT EXISTS departments (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    description VARCHAR(255)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- Table: students
CREATE TABLE IF NOT EXISTS students (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    dob DATE NOT NULL,
    department_id BIGINT NOT NULL,
    CONSTRAINT fk_student_department
        FOREIGN KEY (department_id) REFERENCES departments(id)
        ON DELETE CASCADE
        ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- Table: APP_DETAIL
CREATE TABLE IF NOT EXISTS APP_DETAIL (
    ID VARCHAR(64) PRIMARY KEY,
    NAME VARCHAR(100) NOT NULL,
    DESCRIPTION VARCHAR(255),
    CREATED_TIME DATETIME
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- Table: DOCUMENT
CREATE TABLE IF NOT EXISTS DOCUMENT (
    ID VARCHAR(64) PRIMARY KEY,
    APP_DETAIL_FK VARCHAR(64) NOT NULL,
    NAME VARCHAR(255) NOT NULL,
    PATH VARCHAR(500) NOT NULL,
    OWNER VARCHAR(100),
    VERSION DOUBLE DEFAULT 1.0,
    DELETED BOOLEAN DEFAULT FALSE,
    CREATED_TIME DATETIME,
    MODIFIED_TIME DATETIME,
    ACTIVE BOOLEAN DEFAULT TRUE,
    CONSTRAINT fk_document_app_detail
        FOREIGN KEY (APP_DETAIL_FK) REFERENCES APP_DETAIL(ID)
        ON DELETE RESTRICT
        ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE INDEX idx_document_app_detail_fk ON DOCUMENT(APP_DETAIL_FK);
CREATE INDEX idx_document_deleted ON DOCUMENT(DELETED);
CREATE INDEX idx_document_active ON DOCUMENT(ACTIVE);
